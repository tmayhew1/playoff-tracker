// The wordmark: Trey's own handwriting, photographed and traced to a single
// outline path. The trailing "s" is not the one in that photo — it's the
// rounder "s" from the top-left of the same page, lifted out and set back down
// on the same baseline with a little more air after the apostrophe.
//
// The trace lives in a 409x306 box. The writing baseline — the foot of the T,
// what the rest of a line of type should sit on — is at y=154, a hair over
// halfway down; everything below it is the y's loop. So the mark can't be
// baseline-aligned as-is: a replaced element's baseline is its bottom edge,
// which here is the bottom of that loop. Pulling the descender back off as a
// negative bottom margin puts the writing baseline on the box's margin edge
// instead, and lets the loop hang out of the line box. Whoever places the mark
// owes it that space back — see treysMarkDescender.

const VIEW_W = 409;
const VIEW_H = 306;
const BASELINE_Y = 154;
const DESCENDER = (VIEW_H - BASELINE_Y) / VIEW_H;

/** How far the y's loop hangs below the line, for a mark of this height. */
export function treysMarkDescender(height) {
  return Math.round(height * DESCENDER);
}

